"""Turn results/details/*.csv|json into results/summary.md.

Nothing here is hand-typed: every number in the README section comes from the files written by run_all.py, so the
write-up cannot drift from the results. Run after `python run_all.py compare ablate errors corpus curriculum`.
"""
from __future__ import annotations

import json

import pandas as pd

import config

R, D = config.RESULTS, config.DETAILS


def _read(name):
    p = D / name
    return pd.read_csv(p) if p.exists() else None


def _f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and pd.isna(x)) else f"{x:.{nd}f}"


def _ci(row, prefix="delta"):
    return f"[{_f(row[prefix + '_lo'])}, {_f(row[prefix + '_hi'])}]"


def md_table(df: pd.DataFrame, cols: list[str], nd=3) -> str:
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = "".join("| " + " | ".join(_f(r[c], nd) if isinstance(r[c], float) else str(r[c]) for c in cols) + " |\n"
                   for _, r in df.iterrows())
    return head + body


def _audit_tables() -> list[tuple[str, pd.DataFrame]]:
    """Blinded human audits, if labelled: precision of exact vs semantic hits (Wilson 95% CI)."""
    import corpus_extract as ce
    import curriculum_semantic as cs
    A, out = config.AUDIT, []
    for title, sheet, key, fn in (
            ("Blinded human audit, unseen job ads", A / "job_audit_sheet.csv", A / "job_audit_key.csv", ce.evaluate_job_audit),
            ("Blinded human audit, unit PDFs", A / "curriculum_label_sheet.csv", A / "curriculum_label_key.csv",
             cs.evaluate_unit_labels)):
        if sheet.exists() and key.exists() and ce._has_labels(sheet):
            df = fn(sheet, key)
            if len(df):
                out.append((title, df))
    return out


def main():
    base, mc, mb = _read("baseline_table.csv"), _read("model_comparison.csv"), _read("model_bootstrap.csv")
    abl, curr = _read("ablation.csv"), _read("curriculum_unit_summary.csv")
    if base is None or mc is None or mb is None:
        raise SystemExit("run `python run_all.py verify compare` first")
    S5, S0 = "S5 Baseline++", "S0 Baseline (PhraseMatcher)"
    main_name = f"{config.MAIN_MODEL} hybrid"
    cv_name = f"{config.MAIN_MODEL} hybrid (pool chosen in CV)"
    m = mc.set_index("system")
    b = mb[(mb.system == main_name)]
    bb = lambda vs, metric: b[(b.vs == vs) & (b.metric == metric)].iloc[0]
    b_of = lambda system, metric: mb[(mb.system == system) & (mb.vs == S5) & (mb.metric == metric)].iloc[0]
    s5 = base.set_index("system").loc[S5]
    sm = m.loc[main_name]
    models_only = mc[~mc.semantic_only & ~mc.system.str.contains("pool chosen in CV")]   # one row per embedding model
    best_hybrid = models_only.sort_values("lenient_F1", ascending=False).iloc[0]

    out = ["# Step 4 results (auto-generated by make_report.py)\n"]
    out.append("## Baselines on the 30 gold ads (Step 3 numbers, reproduced)\n")
    out.append(md_table(base, ["system", "strict_P", "strict_R", "strict_F1", "lenient_P", "lenient_R", "lenient_F1", "I_recall"]))
    out.append("\n## Model comparison (leave-one-ad-out tuned, pooled out-of-fold predictions)\n")
    out.append(md_table(mc, ["system", "tau_median", "strict_P", "strict_R", "strict_F1", "lenient_P", "lenient_R",
                             "lenient_F1", "I_recall", "n_added", "added_precision"]))
    if cv_name in m.index:
        out.append(f"\n`{cv_name}`: max vs centroid pooling chosen inside each leave-one-ad-out fold "
                   f"(chosen: {m.loc[cv_name, 'pool_chosen']}). The held-out ad never influences its own pooling; the 30 "
                   f"ads were still examined repeatedly, so this is a consistency check, not an independent test.\n")
    out.append("\n## Paired bootstrap vs Baseline++ (95% CI of the difference, 2,000 resamples over ads)\n")
    vs = mb[mb.vs == S5][["system", "metric", "a", "b", "delta", "delta_lo", "delta_hi", "p_delta_le_0"]]
    out.append(md_table(vs, ["system", "metric", "a", "b", "delta", "delta_lo", "delta_hi", "p_delta_le_0"]))
    if abl is not None:
        out.append("\n## Ablation around the default configuration (main model, out-of-fold)\n")
        out.append(md_table(abl, ["factor", "setting", "tau_median", "strict_F1", "lenient_P", "lenient_R", "lenient_F1",
                                  "I_recall", "n_added", "added_precision"]))
    if curr is not None:
        out.append("\n## Unit PDFs: skills added by the semantic layer\n")
        out.append(md_table(curr, ["unit_id", "n_exact", "n_semantic_added", "added"]))
    audits = _audit_tables()
    for title, df in audits:
        out.append(f"\n## {title}\n")
        out.append(md_table(df, ["source", "n_labelled", "correct", "precision", "ci_lo", "ci_hi"]))
    (R / "summary.md").write_text("\n".join(out))

    print("wrote results/summary.md")


if __name__ == "__main__":
    main()
